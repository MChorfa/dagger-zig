// UserModuleBuildZig returns the build.zig that Codegen writes into the
// user's source tree. It wires dagger_sdk as a path dependency and
// installs a `module` executable via the `module-runtime` step — the
// contract ModuleRuntime expects (entrypoint /out/bin/module).
//
// The user's module entry point is main.zig at the source root. If they
// need a different file, they can rename it or add a build.zig override
// in a future version.
func UserModuleBuildZig() string {
	return `// Auto-generated by dagger-zig codegen. DO NOT EDIT.
// Regenerate with: dagger develop
const std = @import("std");

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});

    const dagger_sdk = b.dependency("dagger_sdk", .{
        .target = target,
        .optimize = optimize,
    });

    const mod = b.createModule(.{
        .root_source_file = b.path("main.zig"),
        .target = target,
        .optimize = optimize,
        .link_libc = true,
        .imports = &.{
            .{ .name = "dagger_sdk", .module = dagger_sdk.module("dagger_sdk") },
        },
    });

    const exe = b.addExecutable(.{
        .name = "module",
        .root_module = mod,
    });
    const install = b.addInstallArtifact(exe, .{});
    const step = b.step("module-runtime", "Install the Dagger module runtime");
    step.dependOn(&install.step);
    b.getInstallStep().dependOn(&install.step);
}
`
}

// UserModuleMainZig returns the main.zig scaffold that InitModule writes
// into a newly initialized module's source directory. The module struct
// name is derived from the module name the user passed to init.
func UserModuleMainZig(moduleName string) string {
	structName := zigStructName(moduleName)
	return `const std = @import("std");
const dagger = @import("dagger_sdk");

const ` + structName + ` = struct {
    /// Returns a greeting. Replace this with your module's real functions.
    pub fn hello(self: *const ` + structName + `, ctx: *dagger.module.Context) ![]const u8 {
        _ = self;
        _ = ctx;
        return "hello from ` + moduleName + `";
    }
};

pub fn main(init: std.process.Init) !void {
    return dagger.module.serve(init, ` + structName + `{});
}
`
}

// zigStructName converts a Dagger module name (kebab-case or snake_case)
// into a valid Zig PascalCase struct identifier. The Dagger Go module
// convention PascalCases the module name; we mirror that.
func zigStructName(moduleName string) string {
	var b strings.Builder
	upper := true
	for _, r := range moduleName {
		if r == '-' || r == '_' || r == '.' || r == ' ' {
			upper = true
			continue
		}
		if upper {
			b.WriteRune(unicode.ToUpper(r))
			upper = false
		} else {
			b.WriteRune(r)
		}
	}
	if b.Len() == 0 {
		return "ZigModule"
	}
	return b.String()
}

