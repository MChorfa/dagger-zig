// UserClientMainZig returns the main.zig scaffold that InitClient writes
// into a generated client's directory. A Zig client uses the same
// dagger_sdk library and connects with dagger.connect().
//
// Zig is statically typed: calling the target module's functions requires
// typed stubs generated from the module's typedefs. This scaffold wires
// the connection layer; module-specific stubs are emitted by `dagger
// generate` once the client generator is implemented.
func UserClientMainZig(moduleName string) string {
	return `const std = @import("std");
const dagger = @import("dagger_sdk");

// Client for the "` + moduleName + `" module.
// Typed bindings for the module's functions are generated by
// 'dagger generate' — this scaffold wires the session connection.
pub fn main(init: std.process.Init) !void {
    const gpa = init.gpa;
    const io = init.io;

    var client = try dagger.connect(gpa, io, .{});
    defer client.close();

    _ = client.dag();
}
`
}
